#!/bin/bash

set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
source "$SCRIPT_DIR/screenshot-names.sh"

device_type=""
only=""
show=0

for arg in "$@"; do
    case "$arg" in
    --show | --headed) show=1 ;;
    *)
        if [ -z "$device_type" ]; then
            device_type="$arg"
        elif [ -z "$only" ]; then
            only="$arg"
        fi
        ;;
    esac
done
device_type="${device_type:-desktop}"

echo "Running screenshot tests with Chrome..."

export FLEXIFY_DEVICE_TYPE="$device_type"
export FLUTTER_DRIVER_DEVICE=chrome

dart_define=()
if [ -n "$only" ]; then
    only="$(screenshot_name "$only")"
    dart_define=(--dart-define=SCREENSHOT_ONLY="$only")
    echo "Capturing only: $only"
fi

chrome_binary=()
[ -n "${FLEXIFY_CHROME_BINARY:-}" ] && chrome_binary=(--chrome-binary="$FLEXIFY_CHROME_BINARY")

headless_flag=(--headless)
[ "$show" -eq 1 ] && headless_flag=()

chromedriver_pid=""
cleanup() {
    [ -n "$chromedriver_pid" ] || return 0
    kill -TERM "$chromedriver_pid" >/dev/null 2>&1 || true
    wait "$chromedriver_pid" 2>/dev/null || true
}
trap cleanup EXIT

if ! curl -s -o /dev/null http://localhost:4444/status; then
    echo "Starting chromedriver on port 4444..."
    chromedriver --verbose --port=4444 >/tmp/flexify-chromedriver.log 2>&1 &
    chromedriver_pid=$!

    for _ in $(seq 1 20); do
        curl -s -o /dev/null http://localhost:4444/status && break
        sleep 0.5
    done

    if ! curl -s -o /dev/null http://localhost:4444/status; then
        echo "ERROR: chromedriver did not become ready on port 4444"
        exit 1
    fi
fi

# Only count screenshots generated by this run.
mkdir -p fastlane/screenshots
if [ -z "$only" ]; then
    rm -f fastlane/screenshots/desktop-{1..8}_en-US.png
fi

# Run Flutter drive command targeting Chrome
if timeout --signal=TERM --kill-after=5s 180s flutter drive \
    --driver=test_driver/integration_test.dart \
    --target=integration_test/screenshot_test.dart \
    "${dart_define[@]}" \
    -d web-server --browser-name=chrome "${headless_flag[@]}" "${chrome_binary[@]}"; then
    :
else
    code=$?
    echo "Flutter driver failed with exit status $code"
    sessions=$(curl -fsS --max-time 3 http://localhost:4444/sessions || true)
    session=$(jq -r '.value[0].id // empty' <<< "$sessions" 2>/dev/null || true)
    if [ -n "$session" ]; then
        echo "ChromeDriver session: $session"
        curl -fsS --max-time 5 -X POST -H 'Content-Type: application/json' \
            -d '{"type":"browser"}' "http://localhost:4444/session/$session/se/log" \
            | jq -r '.value[]?.message // empty' | tail -n 80 || true
        curl -fsS --max-time 5 "http://localhost:4444/session/$session/source" \
            | jq -r '.value // empty' | head -c 4000 || true
        curl -fsS --max-time 10 "http://localhost:4444/session/$session/screenshot" \
            | jq -r '.value // empty' | base64 -d > fastlane/screenshots/desktop-debug.png || true
    fi
    tail -n 35 /tmp/flexify-chromedriver.log || true
    exit "$code"
fi

if [ -z "$only" ]; then
    for number in {1..8}; do
        image="fastlane/screenshots/desktop-${number}_en-US.png"
        test -s "$image"
        file "$image" | grep -q 'PNG image data'
    done
fi

echo "Screenshot tests completed successfully!"
